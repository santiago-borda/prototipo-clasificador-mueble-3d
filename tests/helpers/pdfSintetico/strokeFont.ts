export type Polyline = [number, number][];

const parse = (spec: string): Polyline[] =>
  spec === ""
    ? []
    : spec.split("|").map((stroke) => stroke.split(" ").map((point) => point.split(",").map(Number) as [number, number]));

const GLYPHS = new Map<string, Polyline[]>(Object.entries({ ...BASE, ...COMPOSED }).map(([char, spec]) => [char, parse(spec)]));

/** Polilíneas de un carácter en la grilla; error si el fixture usa un carácter sin glifo (no se dibuja a ciegas). */
export function glyph(char: string): Polyline[] {
  const strokes = GLYPHS.get(char);
  if (!strokes) throw new Error(`La fuente de trazos no tiene el carácter "${char}" (U+${char.codePointAt(0)?.toString(16)}).`);
  return strokes;
}
